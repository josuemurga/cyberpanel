<?php

namespace Imunify360;

/**
 * Native PHP client for the ImunifyEmail quarantine API over the local
 * unix-domain socket. Replaces the legacy execute.py imunifyEmail wrapper.
 *
 * The Apache+PHP path on no-panel hosts cannot use the peercred check that
 * IE-quarantine performs against cPanel/DA/Plesk callers — Apache runs as
 * www-data and there is no setuid bridge. Instead, every request carries a
 * short-lived HS256 JWT (claims: sub, role, iat, exp) signed by a secret
 * shared between this process and IE-quarantine. IE-quarantine validates the
 * token and, on success, treats the token's sub/role as the authenticated
 * identity; on failure it falls back to peercred (which fails for www-data)
 * and rejects the request.
 *
 * Secret lifecycle: the JWT secret is generated by imunifyemail-meta postinst
 * at /etc/imunifyemail/jwt-secret, mode 0640 _imunifyemail:_imunifyemail-jwt.
 * The web-server user (www-data on Debian) is added to the dedicated
 * _imunifyemail-jwt group by the imunifyemail-ui package postinst, so it can
 * read the secret without gaining access to the broader _imunify resources.
 */
class ImunifyEmailClient
{
    const SOCKET_PATH = '/var/run/imunifyemail/quarantine.sock';
    const JWT_SECRET_PATH = '/etc/imunifyemail/jwt-secret';
    const JWT_TTL_SECONDS = 300;
    const SOCKET_TIMEOUT_SECONDS = 30;
    const API_PREFIX = '/quarantine/api/v1';
    const ACCOUNT_NAME_PLACEHOLDER = '{account_name}';

    // Strict allowlist for path segments and account names. Anything that
    // could break URL/HTTP framing or escape the path scope (`.`, `..`,
    // `/`, `?`, whitespace, CRLF, control chars) is rejected. Mirrors the
    // tighter validation in no-cp/dev-server.py.
    // D: without it PCRE lets `$` match before a trailing newline, which
    // would smuggle a raw LF into the HTTP request line on the IE socket.
    const SEGMENT_REGEX = '/^[a-zA-Z0-9_-]+$/D';
    const HTTP_METHODS_ALLOWED = array('GET', 'POST', 'PATCH', 'PUT', 'DELETE');

    private $jwtSecretPath;
    private $socketPath;
    private $cachedSecret;

    public function __construct($jwtSecretPath = null, $socketPath = null)
    {
        $this->jwtSecretPath = $jwtSecretPath !== null
            ? $jwtSecretPath
            : self::JWT_SECRET_PATH;
        $this->socketPath = $socketPath !== null
            ? $socketPath
            : self::SOCKET_PATH;
        $this->cachedSecret = null;
    }

    /**
     * Build a /quarantine/api/v1 URL by substituting the {account_name}
     * placeholder. Every non-placeholder segment is validated against
     * SEGMENT_REGEX before substitution — a user-controlled
     * `..` / `/` / control-char in a later segment cannot escape the
     * intended scope, even though the user-role whitelist only inspects
     * the first two segments.
     *
     * @param array $command path segments (e.g. ['accounts', '{account_name}', 'emails'])
     * @param string $accountName resolved scope owner
     * @return string
     * @throws \InvalidArgumentException on bad segment or empty command
     */
    public function buildUrl(array $command, $accountName)
    {
        if (empty($command)) {
            throw new \InvalidArgumentException(
                'ImunifyEmailClient: empty command path'
            );
        }
        if (!is_string($accountName)
            || !preg_match(self::SEGMENT_REGEX, $accountName)) {
            throw new \InvalidArgumentException(
                'ImunifyEmailClient: invalid accountName'
            );
        }
        $encoded = rawurlencode($accountName);
        $segments = array();
        foreach ($command as $seg) {
            $s = (string) $seg;
            if ($s === self::ACCOUNT_NAME_PLACEHOLDER) {
                $segments[] = $encoded;
                continue;
            }
            if (!preg_match(self::SEGMENT_REGEX, $s)) {
                throw new \InvalidArgumentException(
                    "ImunifyEmailClient: invalid path segment '" . $s . "'"
                );
            }
            $segments[] = $s;
        }
        return self::API_PREFIX . '/' . implode('/', $segments);
    }

    /**
     * Mint a short-lived HS256 JWT for a single IE request.
     *
     * @param string $sub account_name (admin → 'root', user → REMOTE_USER)
     * @param string $role 'admin' or 'user'
     * @param int|null $ttl optional override (seconds)
     * @return string a "header.payload.signature" JWT
     * @throws \InvalidArgumentException on invalid role
     * @throws \RuntimeException when the secret file is missing or empty
     */
    public function mintJwt($sub, $role, $ttl = null)
    {
        if ($role !== 'admin' && $role !== 'user') {
            throw new \InvalidArgumentException(
                "ImunifyEmailClient: unknown role '{$role}'"
            );
        }
        $secret = $this->loadSecret();
        $ttl = $ttl !== null ? (int) $ttl : self::JWT_TTL_SECONDS;
        $now = time();
        $header = array('alg' => 'HS256', 'typ' => 'JWT');
        $payload = array(
            'sub' => (string) $sub,
            'role' => $role,
            'iat' => $now,
            'exp' => $now + $ttl,
        );
        $h = self::base64UrlEncode(json_encode($header));
        $p = self::base64UrlEncode(json_encode($payload));
        $sig = hash_hmac('sha256', $h . '.' . $p, $secret, true);
        return $h . '.' . $p . '.' . self::base64UrlEncode($sig);
    }

    /**
     * Execute a single IE-quarantine API call. Mints a JWT, opens the UDS,
     * sends a minimal HTTP/1.1 request, parses the response.
     *
     * @param string $accountName scope owner (used as JWT sub + URL substitution)
     * @param string $role 'admin' or 'user' (JWT role claim)
     * @param array $command path segments
     * @param string $httpMethod 'GET' / 'POST' / 'PATCH' / 'DELETE' / ...
     * @param array $params query-string + JSON body params (mirrors execute.py)
     * @param string|null $body explicit body override (null → json_encode($params))
     * @return array ['http_status' => int, 'body' => string]
     */
    public function call(
        $accountName, $role, array $command, $httpMethod, array $params,
        $body = null
    ) {
        $methodUpper = strtoupper((string) $httpMethod);
        if (!in_array($methodUpper, self::HTTP_METHODS_ALLOWED, true)) {
            throw new \InvalidArgumentException(
                "ImunifyEmailClient: HTTP method '" . $httpMethod . "' not allowed"
            );
        }
        $jwt = $this->mintJwt($accountName, $role);
        $path = $this->buildUrl($command, $accountName);
        $query = empty($params) ? '' : ('?' . self::buildQueryDoseq($params));
        $bodyStr = $body !== null ? (string) $body : self::encodeBody($params);

        $request = sprintf(
            "%s %s%s HTTP/1.1\r\n"
            . "Host: localhost\r\n"
            . "Authorization: Bearer %s\r\n"
            . "Content-Type: application/json\r\n"
            . "Content-Length: %d\r\n"
            . "Connection: close\r\n"
            . "\r\n%s",
            $methodUpper, $path, $query, $jwt,
            strlen($bodyStr), $bodyStr
        );

        $sock = @stream_socket_client(
            'unix://' . $this->socketPath,
            $errno, $errstr, self::SOCKET_TIMEOUT_SECONDS
        );
        if (!$sock) {
            throw new \RuntimeException(
                "ImunifyEmailClient: cannot connect to {$this->socketPath}: "
                . "[{$errno}] {$errstr}"
            );
        }
        stream_set_timeout($sock, self::SOCKET_TIMEOUT_SECONDS);

        try {
            fwrite($sock, $request);
            $raw = stream_get_contents($sock);
        } finally {
            fclose($sock);
        }

        return self::parseHttpResponse($raw === false ? '' : $raw);
    }

    private function loadSecret()
    {
        if ($this->cachedSecret !== null) {
            return $this->cachedSecret;
        }
        if (!is_readable($this->jwtSecretPath)) {
            throw new \RuntimeException(
                "ImunifyEmailClient: JWT secret unreadable at "
                . $this->jwtSecretPath
            );
        }
        $raw = file_get_contents($this->jwtSecretPath);
        $secret = $raw === false ? '' : rtrim($raw, "\r\n");
        if ($secret === '') {
            throw new \RuntimeException(
                "ImunifyEmailClient: JWT secret is empty at "
                . $this->jwtSecretPath
            );
        }
        $this->cachedSecret = $secret;
        return $secret;
    }

    /**
     * Mirror Python's `urllib.parse.urlencode(params, doseq=True)`: list-valued
     * parameters are emitted as `k=v1&k=v2`, not as PHP's default
     * `k[0]=v1&k[1]=v2`. cPanel's execute.py path uses the doseq form, and the
     * IE-quarantine API parses list query-params in that shape — keep both
     * client paths producing the same wire format (BugBot 55fa3dda).
     *
     * @param array $params
     * @return string
     */
    private static function buildQueryDoseq(array $params)
    {
        $pairs = array();
        foreach ($params as $k => $v) {
            $key = rawurlencode((string) $k);
            if (is_array($v)) {
                foreach ($v as $item) {
                    $pairs[] = $key . '=' . rawurlencode((string) $item);
                }
            } elseif (is_bool($v)) {
                $pairs[] = $key . '=' . ($v ? '1' : '0');
            } elseif ($v === null) {
                $pairs[] = $key . '=';
            } else {
                $pairs[] = $key . '=' . rawurlencode((string) $v);
            }
        }
        return implode('&', $pairs);
    }

    // Serialize the request body as a JSON object, mirroring the cPanel
    // execute.py path (json.dumps of a dict). Casting to object keeps an
    // empty params map an object ({}) rather than json_encode's array ([]),
    // which IE-quarantine rejects when it expects an object.
    private static function encodeBody(array $params)
    {
        return json_encode((object) $params);
    }

    private static function parseHttpResponse($raw)
    {
        $split = explode("\r\n\r\n", $raw, 2);
        $head = $split[0];
        $body = isset($split[1]) ? $split[1] : '';

        if (!preg_match('#^HTTP/\d\.\d\s+(\d+)#', $head, $m)) {
            throw new \RuntimeException(
                "ImunifyEmailClient: malformed HTTP response"
            );
        }
        $status = (int) $m[1];

        if (preg_match('/^Transfer-Encoding:\s*chunked/im', $head)) {
            $body = self::decodeChunked($body);
        }

        return array('http_status' => $status, 'body' => $body);
    }

    private static function decodeChunked($body)
    {
        $out = '';
        $offset = 0;
        $len = strlen($body);
        while ($offset < $len) {
            $eol = strpos($body, "\r\n", $offset);
            if ($eol === false) {
                break;
            }
            $sizeHex = trim(substr($body, $offset, $eol - $offset));
            // Strip optional chunk extension.
            if (($semi = strpos($sizeHex, ';')) !== false) {
                $sizeHex = substr($sizeHex, 0, $semi);
            }
            $size = hexdec($sizeHex);
            $offset = $eol + 2;
            if ($size <= 0) {
                break;
            }
            $out .= substr($body, $offset, $size);
            $offset += $size + 2;
        }
        return $out;
    }

    private static function base64UrlEncode($data)
    {
        return rtrim(strtr(base64_encode($data), '+/', '-_'), '=');
    }
}
